#!/usr/bin/env node
import esbuild from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const pkgRoot = path.resolve(__dirname, '..')
const metaPath = path.join(pkgRoot, 'src/icons/iconography.meta.ts')
const legacyPath = path.join(pkgRoot, 'src/icons/iconography.legacy.ts')
const iconFilesPath = path.join(pkgRoot, 'src/icons/iconFiles.ts')
const iconRegistryEntryPath = path.join(pkgRoot, 'src/icons/iconRegistry.entry.ts')
const iconRegistryBundlePath = path.join(pkgRoot, 'src/icons/iconRegistry.bundle.js')
const iconRegistryTypesPath = path.join(pkgRoot, 'src/icons/iconRegistry.bundle.d.ts')
const legacyIconRegistryPath = path.join(pkgRoot, 'src/icons/iconRegistry.ts')
const iconLoadersPath = path.join(pkgRoot, 'src/icons/iconLoaders.ts')
const shimsDir = path.join(pkgRoot, 'src/icons/shims')
const loadersDir = path.join(pkgRoot, 'src/icons/loaders')
const legacyLoadersPath = path.join(pkgRoot, 'src/icons/iconography.loaders.ts')

function resolveLucideMain() {
  const candidates = [
    path.join(pkgRoot, 'node_modules/@lucide/vue/dist/esm/lucide-vue.mjs'),
    path.resolve(pkgRoot, '../../node_modules/@lucide/vue/dist/esm/lucide-vue.mjs'),
  ]
  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) return candidate
  }
  throw new Error('@lucide/vue not found. Run npm install first.')
}

function parseMeta(source) {
  const entryRe = /\{\s*name:\s*'([^']+)',\s*label:\s*'([^']+)'\s*\}/g
  const items = []
  let match
  while ((match = entryRe.exec(source))) {
    items.push({ name: match[1], label: match[2] })
  }
  return items
}

function parseLegacyWithComponents(source) {
  const entryRe =
    /\{\s*name:\s*'([^']+)',\s*label:\s*'([^']+)',\s*component:\s*(\w+)\s*\}/g
  const items = []
  let match
  while ((match = entryRe.exec(source))) {
    items.push({ name: match[1], label: match[2], component: match[3] })
  }
  return items
}

function parseLucideExportMap(lucideMainSource) {
  const lineRe = /export\s*\{([^}]+)\}\s*from\s*'\.\/icons\/([^']+)\.(?:js|mjs)'/g
  const nameToFile = new Map()
  const fileToNames = new Map()
  let match
  while ((match = lineRe.exec(lucideMainSource))) {
    const exportNames = match[1]
    const file = match[2]
    const names = []
    const nameRe = /default as (\w+)/g
    let nameMatch
    while ((nameMatch = nameRe.exec(exportNames))) {
      const component = nameMatch[1]
      if (!nameToFile.has(component)) nameToFile.set(component, file)
      names.push(component)
    }
    fileToNames.set(file, names)
  }
  return { nameToFile, fileToNames }
}

function resolveIconFile(name, component, nameToFile, fileToNames) {
  if (component && nameToFile.has(component)) {
    return nameToFile.get(component)
  }
  if (fileToNames.has(name)) return name
  for (const [file, names] of fileToNames) {
    if (file === name || names.some((n) => n.toLowerCase() === name.replace(/-/g, ''))) {
      return file
    }
  }
  const pascal = name
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
  if (nameToFile.has(pascal)) return nameToFile.get(pascal)
  return null
}

function lucideComponentName(item, fileToNames) {
  if (item.component) return item.component
  const names = fileToNames.get(item.file)
  if (names?.length) return names[0]
  return item.name
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
}

async function writeIconFiles(items) {
  const lucideMain = fs.readFileSync(resolveLucideMain(), 'utf8')
  const { nameToFile, fileToNames } = parseLucideExportMap(lucideMain)
  const missing = []

  for (const item of items) {
    item.file = resolveIconFile(item.name, item.component, nameToFile, fileToNames)
    if (!item.file) missing.push(item)
  }

  if (missing.length > 0) {
    const sample = missing
      .slice(0, 10)
      .map((item) => item.name)
      .join(', ')
    throw new Error(
      `Could not resolve lucide file for ${missing.length} icon(s): ${sample}`,
    )
  }

  if (!fs.existsSync(metaPath)) {
    const metaLines = items.map(
      (item) => `  { name: '${item.name}', label: '${item.label}' },`,
    )
    fs.writeFileSync(
      metaPath,
      `/** Generated by scripts/generate-icon-loaders.mjs — do not edit manually. */
export const iconographyMeta = [
${metaLines.join('\n')}
] as const

export type IconographyName = (typeof iconographyMeta)[number]['name']
`,
    )
  }

  const fileLines = items.map(
    (item) => `  '${item.name}': '${item.file}',`,
  )

  fs.writeFileSync(
    iconFilesPath,
    `/** Generated by scripts/generate-icon-loaders.mjs — do not edit manually. */
import type { IconographyName } from './iconography.meta'

/** Lucide ESM file stem per catalog icon name (no extension). */
export const iconFiles: Record<IconographyName, string> = {
${fileLines.join('\n')}
}
`,
  )

  const importByFile = new Map()
  for (const item of items) {
    if (!importByFile.has(item.file)) {
      importByFile.set(item.file, lucideComponentName(item, fileToNames))
    }
  }

  const importLines = [...importByFile.entries()].map(
    ([file, ident]) =>
      `import ${ident}Icon from '@lucide/vue/dist/esm/icons/${file}.mjs'`,
  )

  const registryLines = items.map((item) => {
    const ident = importByFile.get(item.file)
    return `  '${item.name}': ${ident}Icon,`
  })

  fs.writeFileSync(
    iconRegistryEntryPath,
    `/** Generated by scripts/generate-icon-loaders.mjs — esbuild entry only, do not import directly. */
import type { Component } from 'vue'
import type { IconographyName } from './iconography.meta'

${importLines.join('\n')}

export const iconRegistry: Record<IconographyName, Component> = {
${registryLines.join('\n')}
}
`,
  )

  fs.writeFileSync(
    iconRegistryTypesPath,
    `/** Generated by scripts/generate-icon-loaders.mjs — do not edit manually. */
import type { Component } from 'vue'
import type { IconographyName } from './iconography.meta'

export declare const iconRegistry: Record<IconographyName, Component>
`,
  )

  await esbuild.build({
    entryPoints: [iconRegistryEntryPath],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    outfile: iconRegistryBundlePath,
    external: ['vue'],
    logLevel: 'silent',
  })

  if (fs.existsSync(legacyIconRegistryPath)) {
    fs.unlinkSync(legacyIconRegistryPath)
  }

  if (fs.existsSync(shimsDir)) {
    fs.rmSync(shimsDir, { recursive: true, force: true })
  }

  if (fs.existsSync(iconLoadersPath)) {
    fs.unlinkSync(iconLoadersPath)
  }

  if (fs.existsSync(loadersDir)) {
    fs.rmSync(loadersDir, { recursive: true, force: true })
  }

  if (fs.existsSync(legacyLoadersPath)) {
    fs.unlinkSync(legacyLoadersPath)
  }

  console.log(
    `Generated iconFiles.ts (${items.length} icons) -> ${path.relative(pkgRoot, iconFilesPath)}`,
  )
  console.log(
    `Generated iconRegistry.entry.ts (${items.length} icons) -> ${path.relative(pkgRoot, iconRegistryEntryPath)}`,
  )
  const bundleKb = (fs.statSync(iconRegistryBundlePath).size / 1024).toFixed(1)
  console.log(
    `Bundled iconRegistry.bundle.js (${bundleKb} kB) -> ${path.relative(pkgRoot, iconRegistryBundlePath)}`,
  )
}

async function main() {
  let items
  if (fs.existsSync(metaPath)) {
    items = parseMeta(fs.readFileSync(metaPath, 'utf8'))
  } else if (fs.existsSync(legacyPath)) {
    items = parseLegacyWithComponents(fs.readFileSync(legacyPath, 'utf8'))
  } else {
    throw new Error('Missing iconography.meta.ts (and no iconography.legacy.ts fallback).')
  }

  await writeIconFiles(items)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
